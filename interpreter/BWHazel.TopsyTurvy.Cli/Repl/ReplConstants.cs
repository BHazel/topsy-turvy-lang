namespace BWHazel.TopsyTurvy.Cli.Repl;

/// <summary>
/// Defines constants for REPL control commands.
/// </summary>
internal static class ReplConstants
{
    /// <summary>
    /// Primary exit command.
    /// </summary>
    public const string Exit = ":exit";

    /// <summary>
    /// Alias for <see cref="Exit"/>.
    /// </summary>
    public const string Quit = ":quit";

    /// <summary>
    /// Primary screen-clear command.
    /// </summary>
    public const string Begone = ":begone";

    /// <summary>
    /// Alias for <see cref="Begone"/>.
    /// </summary>
    public const string Clear = ":clear";

    /// <summary>
    /// Primary help command.
    /// </summary>
    public const string Entracte = ":entracte";

    /// <summary>
    /// Alias for <see cref="Entracte"/>.
    /// </summary>
    public const string Help = ":help";

    /// <summary>
    /// Primary multi-line mode command.
    /// </summary>
    public const string Madrigal = ":madrigal";

    /// <summary>
    /// Alias for <see cref="Madrigal"/>.
    /// </summary>
    public const string MultiLine = ":multiline";

    /// <summary>
    /// Primary single-line mode command.
    /// </summary>
    public const string Patter = ":patter";

    /// <summary>
    /// Alias for <see cref="Patter"/>.
    /// </summary>
    public const string SingleLine = ":singleline";
}
