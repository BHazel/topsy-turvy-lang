    /// <summary>
    /// Builds label text describing an expression, without emitting any instructions.
    /// </summary>
    /// <remarks>
    /// A construct label needs its text before the real instructions for the expression are emitted, so
    /// this walks the expression tree directly instead of reading from already-emitted
    /// instructions.
    /// </remarks>
    /// <param name="expression">The expression to build label text for.</param>
    /// <returns>The formatted label text.</returns>
    /// <exception cref="NotSupportedException">Thrown when the expression type has no label text representation.</exception>
    private string BuildConditionText(Expression expression) => expression switch
    {
        LiteralNode literal => this.labelFormatter.FormatText(this.OperandName(new LiteralOperand(literal.Value!))),
        IdentifierNode identifier => this.labelFormatter.FormatText(identifier.Name),
        PrefixExpressionNode prefix when prefix.Arguments.Count == 1 =>
            this.labelFormatter.FormatText(this.MnemonicForOperator(prefix.Operator), this.RawOperandText(prefix.Arguments[0])),
        PrefixExpressionNode prefix =>
            this.labelFormatter.FormatText(this.MnemonicForOperator(prefix.Operator), this.RawOperandText(prefix.Arguments[0]), this.RawOperandText(prefix.Arguments[1])),
        ExpressionCastNode cast => this.BuildConditionText(cast.Expression),
        _ => throw new NotSupportedException($"Expression type '{expression.GetType().Name}' has no label text representation.")
    };

    /// <summary>
    /// Returns the unformatted text for a single operand of a <see cref="PrefixExpressionNode"/>,
    /// used by <see cref="BuildConditionText"/>.
    /// </summary>
    /// <param name="expression">The operand expression.</param>
    /// <returns>
    /// For a <see cref="LiteralNode"/>, its raw value text. For an <see cref="IdentifierNode"/>,
    /// its name. For a nested <see cref="PrefixExpressionNode"/>, the text from a recursive
    /// <see cref="BuildConditionText"/> call.
    /// </returns>
    /// <exception cref="NotSupportedException">Thrown when the expression type cannot be used as a label operand.</exception>
    private string RawOperandText(Expression expression) => expression switch
    {
        LiteralNode literal => this.OperandName(new LiteralOperand(literal.Value!)),
        IdentifierNode identifier => identifier.Name,
        PrefixExpressionNode nested => this.BuildConditionText(nested),
        ExpressionCastNode cast => this.RawOperandText(cast.Expression),
        _ => throw new NotSupportedException($"Expression type '{expression.GetType().Name}' cannot be used as a label operand.")
    };

    /// <summary>
    /// Returns the plain (non-<c>.f</c>) UtopIR mnemonic for an operator, used to build label text.
    /// </summary>
    /// <param name="theOperator">The operator to map.</param>
    /// <returns>The plain UtopIR mnemonic string.</returns>
    /// <exception cref="NotSupportedException">Thrown when <paramref name="theOperator"/> has no label mnemonic.</exception>
    private string MnemonicForOperator(Operator theOperator)
    {
        if (this.IsArithmeticOperator(theOperator))
        {
            return this.OperationMnemonic(this.MapOperator(theOperator));
        }

        if (theOperator == Operator.InversionOf)
        {
            return UtopIRKeywords.Instructions.Inv;
        }

        if (theOperator is Operator.TranspositionUp or Operator.TranspositionDown)
        {
            return this.BitwiseOperationMnemonic(theOperator == Operator.TranspositionUp
                ? UtopIRBitwiseOperation.TransUp
                : UtopIRBitwiseOperation.TransDown);
        }

        if (this.IsBitwiseOperator(theOperator))
        {
            return this.BitwiseOperationMnemonic(this.MapBitwiseOperator(theOperator));
        }

        if (this.IsComparisonOperator(theOperator))
        {
            return this.ComparisonOperationMnemonic(this.MapComparisonOperator(theOperator));
        }

        if (theOperator == Operator.HardlyEver)
        {
            return UtopIRKeywords.Instructions.Hardly;
        }

        if (this.IsLogicalOperator(theOperator))
        {
            return this.LogicalOperationMnemonic(this.MapLogicalOperator(theOperator));
        }

        throw new NotSupportedException($"Operator '{theOperator}' has no label mnemonic.");
    }

    /// <summary>
    /// Builds label text for the literal value of a switch case.
    /// </summary>
    /// <param name="literal">The raw case literal value.</param>
    /// <returns>The formatted label text.</returns>
    private string SwitchCaseExpressionText(object? literal) =>
        this.labelFormatter.FormatText(literal is null ? "0" : this.OperandName(new LiteralOperand(literal)));

    /// <summary>
    /// Infers the <see cref="UtopIRType"/> an expression would produce if transformed, without
    /// emitting any instructions.
    /// </summary>
    /// <remarks>
    /// Needed by ternary lowering: the type of both branches must be known before the shared
    /// temporary register is declared with <c>welcome</c> but only one branch is ever actually transformed.
    /// </remarks>
    /// <param name="expression">The expression to infer a type for.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>.</param>
    /// <returns>The <see cref="UtopIRType"/> the expression would produce.</returns>
    /// <exception cref="NotSupportedException">Thrown when the expression type has no inferable type.</exception>
    private UtopIRType InferExpressionType(Expression expression, Dictionary<string, UtopIRType> declaredTypes) => expression switch
    {
        LiteralNode literal => this.InferOperandType(new LiteralOperand(literal.Value!), declaredTypes),
        IdentifierNode identifier => declaredTypes[identifier.Name],
        PrefixExpressionNode prefix when prefix.Operator == Operator.InversionOf => this.InferExpressionType(prefix.Arguments[0], declaredTypes),
        PrefixExpressionNode prefix when prefix.Operator is Operator.TranspositionUp or Operator.TranspositionDown => this.InferExpressionType(prefix.Arguments[0], declaredTypes),
        PrefixExpressionNode prefix when this.IsComparisonOperator(prefix.Operator) || this.IsLogicalOperator(prefix.Operator) => UtopIRType.Decree,
        PrefixExpressionNode prefix when this.IsArithmeticOperator(prefix.Operator) || this.IsBitwiseOperator(prefix.Operator) => this.Widen(this.InferExpressionType(prefix.Arguments[0], declaredTypes), this.InferExpressionType(prefix.Arguments[1], declaredTypes)),
        ExpressionCastNode cast => this.MapType(cast.NewType),
        _ => throw new NotSupportedException($"Expression type '{expression.GetType().Name}' has no inferable type.")
    };
}
