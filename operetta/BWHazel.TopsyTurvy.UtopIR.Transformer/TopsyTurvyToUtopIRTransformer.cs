namespace BWHazel.TopsyTurvy.UtopIR.Transformer;

/// <summary>
/// Transforms a Topsy Turvy AST (<see cref="ProgramNode"/>) into a flat UtopIR instruction
/// sequence (<see cref="UtopIRProgram"/>).
/// </summary>
/// <remarks>
/// <para>
/// The transformer uses type-switching, consistent with the existing interpreter and
/// type checker in the Topsy Turvy toolchain.
/// </para>
/// <para>
/// Nested expressions such as <c>SUM OF PRODUCT OF a AND b AND c</c> are flattened into
/// a sequence of arithmetic instructions using auto-generated temporary virtual registers.
/// Naming is delegated to an <see cref="ITemporaryVariableNameFormatter"/>, supplied via
/// the constructor, by default an <see cref="IncrementingIntVariableFormatter"/>.
/// </para>
/// <para>
/// ## Widening
/// Mixed-type arithmetic, e.g. <c>SUM OF &lt;peer&gt; AND &lt;chancellor&gt;</c>, is
/// legal in Topsy Turvy.  The result type is the wider of the two operand types, matching the
/// <c>TypeCheckVisitor.Widen</c> ordering, an independent copy, consistent with this project
/// existing pattern of per-layer widening tables.  When an <see cref="ArithmeticInstruction"/>
/// operands would otherwise differ in type, the narrower operand is cast into a temporary register
/// via an inserted <see cref="WereInstruction"/> before the arithmetic instruction is emitted, so
/// every <see cref="ArithmeticInstruction"/> the transformer produces always has matching operand types.
/// </para>
/// <para>
/// ## Scope
/// This implementation covers the instruction set defined in UtopIR v0.0.1-preview4: variable
/// declaration/assignment, integer and floating-point arithmetic operations, bitwise operations,
/// comparison and logical operations, control-flow statements (<c>SHOULD IT TRANSPIRE THAT</c>
/// conditionals, ternary expressions, <c>YEOMAN</c> guard clauses, <c>IN WHICH CAPACITY?</c>
/// switch blocks, all four <c>BY A LEGAL FICTION</c> loop kinds, <c>THAT WILL DO.</c> break and
/// <c>ONCE MORE.</c> continue), top-level programme return, <c>yarn</c> character access and array
/// declaration/element access/element assignment, both via the shared <c>VICTIM &lt;index&gt; ON
/// &lt;name&gt;</c> syntax dispatched on the referenced variable recorded type, and pointer
/// declaration/address-of/dereference/write-through/arithmetic. Control-flow statements are
/// lowered into <c>sail</c>/<c>sailalike</c>/<c>sailunlike</c>/label sequences, with label text
/// generated by an <see cref="ILabelNameFormatter"/> supplied via the constructor, by default a
/// <see cref="InstructionIncrementingDetailLabelNameFormatter"/>. Break and continue targets are resolved via an
/// instance-scoped pair of label stacks rather than being threaded as parameters. A function call, resolved
/// via the <see cref="BindingCatalogue"/> supplied to the constructor, lowers to
/// <c>prentice</c>/<c>summon</c>/<c>summon.find</c>. A user-defined function name always takes
/// priority over a same-named function from that catalogue, matching how the interpreter and type
/// checker resolve the same name clash. <c>BEHOLD</c> a plain string literal or <c>yarn</c>-typed variable,
/// and <c>PRAY TELL</c>, lower to a call to the catalogue <c>PreviewBehold</c>/<c>PreviewPrayTell</c>
/// functions respectively (see <see cref="TransformPrint"/>/<see cref="TransformInput"/>); these two
/// keyword-triggered calls are not subject to the shadowing rule above, since the programme never chose
/// the name being called.
/// </para>
/// <para>
/// ## Current Limitations
/// Lowering a call to a user-defined function body is not yet supported by this transformer,
/// regardless of the shadowing rule above. <c>BEHOLD</c> of a non-<c>yarn</c> value (or of a string with
/// a <c>{...}</c> interpolation placeholder) is not yet supported, since neither a general to-string
/// conversion nor interpolation has a UtopIR lowering yet (see <see cref="TransformPrint"/>); a Standard
/// Library conversion function is expected to close the to-string gap in a later version, letting
/// <c>BEHOLD</c> of any type lower to a <c>summon.find</c> call converting it to <c>yarn</c> first.
/// Constant inlining is deferred to a later version.
/// </para>
/// <para>
/// ## Constants
/// Topsy Turvy <c>CONSERVATIVE</c> declarations are currently lowered
/// identically to mutable declarations.  Constant inlining (replacing every reference with
/// its literal value) requires a full symbol-table pass and is deferred.
/// </para>
/// </remarks>
/// <param name="formatter">The formatter used to name temporary virtual registers, or <c>null</c> to use a fresh <see cref="IncrementingIntVariableFormatter"/>.
/// </param>
/// <param name="labelFormatter">The formatter used to name labels, or <c>null</c> to use a fresh <see cref="InstructionIncrementingDetailLabelNameFormatter"/>.
/// </param>
/// <param name="externalFunctions">The catalogue of external functions available to <c>SUMMON</c>, or <c>null</c> to use <see cref="BindingCatalogue.Default"/>.</param>
public sealed class TopsyTurvyToUtopIRTransformer(ITemporaryVariableNameFormatter? formatter = null, ILabelNameFormatter? labelFormatter = null, BindingCatalogue? externalFunctions = null)
{
    private readonly ITemporaryVariableNameFormatter formatter = formatter ?? new IncrementingIntVariableFormatter();
    private readonly ILabelNameFormatter labelFormatter = labelFormatter ?? new InstructionIncrementingDetailLabelNameFormatter();
    private readonly BindingCatalogue externalFunctions = externalFunctions ?? BindingCatalogue.Default;

    /// <summary>
    /// The closing label of the innermost enclosing switch or loop, if any, that a <c>THAT WILL
    /// DO.</c> break statement branches to.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Both switch and every loop kind push their own closing label here around their body
    /// transformation, and pop it afterwards, so the top of the stack is always the correct target
    /// for a break at any nesting depth.
    /// </para>
    /// <para>
    /// For example, a switch nested in a loop pushes after the loop, so a break inside the switch
    /// correctly targets the switch, not the loop.
    /// </para>
    /// </remarks>
    private readonly Stack<UtopIRLabel> breakTargets = new();

    /// <summary>
    /// The continue target of the innermost enclosing loop, if any, that a <c>ONCE MORE.</c>
    /// continue statement branches to.
    /// </summary>
    /// <remarks>
    /// Only loop methods push here, never a switch.  A continue inside a switch nested in a
    /// loop must still reach the loop, skipping the switch entirely.
    /// </remarks>
    private readonly Stack<UtopIRLabel> continueTargets = new();

    /// <summary>
    /// The map from array variable name to its declared element <see cref="UtopIRType"/>.
    /// </summary>
    /// <remarks>
    /// Keyed separately from <c>declaredTypes</c>, since that map only ever records the
    /// <see cref="UtopIRType.Array"/> marker for an array variable, not its true element type.
    /// Reset at the start of every <see cref="Transform"/> call, and instance-scoped rather
    /// than threaded as a parameter, so that <see cref="TransformExpression"/> and every method that calls it
    /// did not need a new parameter added to their signatures just to look up an array element type.
    /// </remarks>
    private Dictionary<string, UtopIRType> arrayElementTypes = [];

    /// <summary>
    /// The map from pointer variable name to its declared pointee <see cref="UtopIRType"/>.
    /// </summary>
    /// <remarks>
    /// Keyed separately from <c>declaredTypes</c>: that map only ever records the
    /// <see cref="UtopIRType.Pointer"/> marker, not the true pointee type. Reset at the start of every
    /// <see cref="Transform"/> call, and instance-scoped rather than threaded as a parameter, for the
    /// same reason as <see cref="arrayElementTypes"/>.
    /// </remarks>
    private Dictionary<string, UtopIRType> pointerPointeeTypes = [];

    /// <summary>
    /// The names of every user-defined function in the programme, including nested ones.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Reset at the start of every <see cref="Transform"/> call.  <see cref="ResolveSummon"/> checks a
    /// summoned name against this set before consulting the function catalogue, so that a name defined
    /// by the programme itself always takes priority over a same-named catalogue function.
    /// </para>
    /// <para>
    /// Current limitation: since lowering a call to a user-defined function body is not yet
    /// supported (see the class-level remarks), a summoned name found in this set currently causes
    /// <see cref="ResolveSummon"/> to fail rather than resolve to a catalogue function, even when one with
    /// the same name exists.
    /// </para>
    /// </remarks>
    private HashSet<string> userFunctionNames = [];

    /// <summary>
    /// Matches a Topsy Turvy <c>{...}</c> string interpolation placeholder.
    /// </summary>
    /// <remarks>
    /// Mirrors the <c>Interpreter.Interpolate</c> pattern. Used by <see cref="TransformPrint"/> to
    /// reject a <c>BEHOLD</c> whose text would need runtime interpolation, which has no UtopIR lowering yet.
    /// </remarks>
    private static readonly Regex InterpolationPlaceholder = new(@"\{[^}]+\}");

    /// <summary>
    /// Defines the order of numeric <see cref="UtopIRType"/> variants for widening conversions
    /// where index 0 is widest, mirroring <c>TypeCheckVisitor.NumericWideningOrder</c>.
    /// </summary>
    private static readonly UtopIRType[] NumericWideningOrder =
    [
        UtopIRType.Fathom,
        UtopIRType.Foot,
        UtopIRType.StandingChancellor,
        UtopIRType.Chancellor,
        UtopIRType.StandingPeer,
        UtopIRType.Peer,
        UtopIRType.StandingPirate,
        UtopIRType.Pirate,
        UtopIRType.StandingSausageRoll,
        UtopIRType.SausageRoll
    ];

    /// <summary>
    /// Transforms the given Topsy Turvy programme into a <see cref="UtopIRProgram"/>.
    /// </summary>
    /// <param name="program">The root AST node of the Topsy Turvy programme to transform.</param>
    /// <returns>A <see cref="UtopIRProgram"/> containing the equivalent UtopIR instruction sequence.</returns>
    /// <exception cref="NotSupportedException">
    /// Thrown when the programme contains an expression type that is not yet supported by the transformer.
    /// </exception>
    public UtopIRProgram Transform(ProgramNode program)
    {
        List<UtopIRInstruction> instructions = [];
        Dictionary<string, UtopIRType> declaredTypes = [];
        this.arrayElementTypes = [];
        this.pointerPointeeTypes = [];
        this.userFunctionNames = CollectFunctionNames(program.Statements);

        foreach (Statement statement in program.Statements)
        {
            this.TransformStatement(statement, instructions, declaredTypes);
        }

        return new UtopIRProgram(instructions);
    }

    /// <summary>
    /// Dispatches a single top-level or block-level statement for transformation.
    /// </summary>
    /// <param name="statement">The statement to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    private void TransformStatement(Statement statement, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        switch (statement)
        {
            case PrincipalBlockNode principalBlock:
                foreach (Statement declaration in principalBlock.Declarations)
                {
                    this.TransformStatement(declaration, instructions, declaredTypes);
                }

                break;
            case DeclarationNode declaration:
                this.TransformDeclaration(declaration, instructions, declaredTypes);
                break;
            case AssignmentNode assignment:
                this.TransformAssignment(assignment, instructions, declaredTypes);
                break;
            case ArrayDeclarationNode arrayDeclaration:
                this.TransformArrayDeclaration(arrayDeclaration, instructions, declaredTypes);
                break;
            case ArrayElementAssignmentNode arrayElementAssignment:
                this.TransformArrayElementAssignment(arrayElementAssignment, instructions, declaredTypes);
                break;
            case PointerDeclarationNode pointerDeclaration:
                this.TransformPointerDeclaration(pointerDeclaration, instructions, declaredTypes);
                break;
            case DereferenceAssignmentNode dereferenceAssignment:
                this.TransformDereferenceAssignment(dereferenceAssignment, instructions, declaredTypes);
                break;
            case ProgrammeReturnNode programmeReturn:
                this.TransformProgrammeReturn(programmeReturn, instructions, declaredTypes);
                break;
            case ConditionalNode conditional:
                this.TransformConditional(conditional, instructions, declaredTypes);
                break;
            case GuardNode guard:
                this.TransformGuard(guard, instructions, declaredTypes);
                break;
            case SwitchNode switchNode:
                this.TransformSwitch(switchNode, instructions, declaredTypes);
                break;
            case LoopNode loop:
                this.TransformLoop(loop, instructions, declaredTypes);
                break;
            case BreakNode:
                this.TransformBreak(instructions);
                break;
            case ContinueNode:
                this.TransformContinue(instructions);
                break;
            case PrintNode print:
                this.TransformPrint(print, instructions, declaredTypes);
                break;
            case InputNode input:
                this.TransformInput(input, instructions, declaredTypes);
                break;
            case ExpressionStatement { Expression: PrefixExpressionNode { Operator: Operator.Summon } prefix }:
                this.TransformSummonStatement(prefix, instructions, declaredTypes);
                break;
            case ExpressionStatement expressionStatement:
                throw new NotSupportedException(
                    $"Expression statement of type '{expressionStatement.Expression.GetType().Name}' " +
                    "is not supported by the transformer in this version.");
        }
    }

    /// <summary>
    /// Transforms a <see cref="DeclarationNode"/> into a <see cref="WelcomeInstruction"/>
    /// followed by an optional <see cref="AppointInstruction"/> when an initial value is present.
    /// </summary>
    /// <remarks>
    /// When the declared type is an integer type and the initial value inferred type differs (most
    /// commonly because integer literals default to <see cref="UtopIRType.Peer"/>/<see cref="UtopIRType.Chancellor"/>
    /// regardless of the declared target type), a <see cref="WereInstruction"/> cast is inserted via
    /// <see cref="CastOperandIfNeeded"/> so the emitted <see cref="AppointInstruction"/> never stores a
    /// mismatched-width value directly.
    /// </remarks>
    /// <param name="declaration">The declaration statement to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    private void TransformDeclaration(DeclarationNode declaration, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        UtopIRVariable target = new(declaration.Name);
        UtopIRType type = this.MapType(declaration.Type);
        instructions.Add(new WelcomeInstruction(target, type));
        declaredTypes[declaration.Name] = type;

        if (declaration.InitialValue is not null)
        {
            UtopIROperand value = this.TransformExpression(declaration.InitialValue, instructions, declaredTypes);
            if (this.IsCastableType(type))
            {
                UtopIRType valueType = this.InferOperandType(value, declaredTypes);
                value = this.CastOperandIfNeeded(value, valueType, type, instructions, declaredTypes);
            }

            instructions.Add(new AppointInstruction(target, value));
        }
    }

    /// <summary>
    /// Transforms an <see cref="AssignmentNode"/> into an <see cref="AppointInstruction"/>,
    /// flattening the right-hand-side expression first if needed.
    /// </summary>
    /// <remarks>
    /// An <see cref="AddressOfExpressionNode"/> right-hand side is handled as a separate case, emitting
    /// a <see cref="PicturetoInstruction"/> targeting the assignment target directly, rather than going
    /// through <see cref="TransformExpression"/>: <c>pictureto</c> only ever targets an already
    /// declared variable, never a temporary register.  Otherwise, the value is cast to the declared
    /// type of the target when needed, the same as <see cref="TransformDeclaration"/>. The target is
    /// already declared by the time an assignment can reference it.
    /// </remarks>
    /// <param name="assignment">The assignment statement to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    private void TransformAssignment(AssignmentNode assignment, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        UtopIRVariable target = new(assignment.Target);

        if (assignment.Value is AddressOfExpressionNode addressOf)
        {
            instructions.Add(new PicturetoInstruction(target, new UtopIRVariable(addressOf.VariableName)));
            return;
        }

        UtopIROperand value = this.TransformExpression(assignment.Value, instructions, declaredTypes);
        UtopIRType targetType = declaredTypes[assignment.Target];
        if (this.IsCastableType(targetType))
        {
            UtopIRType valueType = this.InferOperandType(value, declaredTypes);
            value = this.CastOperandIfNeeded(value, valueType, targetType, instructions, declaredTypes);
        }

        instructions.Add(new AppointInstruction(target, value));
    }

    /// <summary>
    /// Transforms an <see cref="ArrayDeclarationNode"/> into a <see cref="WelcomeListInstruction"/>
    /// followed by one <see cref="AppointVictimInstruction"/> per initial value, when present.
    /// </summary>
    /// <remarks>
    /// The declared size is <see cref="ArrayDeclarationNode.Size"/> when set, otherwise the count of
    /// <see cref="ArrayDeclarationNode.InitialValues"/> (zero for neither). Records the element type in
    /// <see cref="arrayElementTypes"/>, since <paramref name="declaredTypes"/> only ever records the
    /// <see cref="UtopIRType.Array"/> marker for this variable, not its true element type.
    /// </remarks>
    /// <param name="declaration">The array declaration statement to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    private void TransformArrayDeclaration(ArrayDeclarationNode declaration, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        UtopIRVariable target = new(declaration.Name);
        UtopIRType elementType = this.MapType(declaration.ElementType);
        int size = declaration.Size ?? declaration.InitialValues.Count;

        instructions.Add(new WelcomeListInstruction(target, elementType, size));
        declaredTypes[declaration.Name] = UtopIRType.Array;
        this.arrayElementTypes[declaration.Name] = elementType;

        for (int i = 0; i < declaration.InitialValues.Count; i++)
        {
            UtopIROperand value = this.TransformExpression(declaration.InitialValues[i], instructions, declaredTypes);
            if (this.IsCastableType(elementType))
            {
                UtopIRType valueType = this.InferOperandType(value, declaredTypes);
                value = this.CastOperandIfNeeded(value, valueType, elementType, instructions, declaredTypes);
            }

            instructions.Add(new AppointVictimInstruction(target, new LiteralOperand(i + 1), value));
        }
    }

    /// <summary>
    /// Transforms an <see cref="ArrayElementAssignmentNode"/> into an <see cref="AppointVictimInstruction"/>,
    /// flattening the index and value expressions first if needed.
    /// </summary>
    /// <remarks>
    /// Casts the value to the declared element type of the array when needed, the same as
    /// <see cref="TransformAssignment"/>. The array is already declared by the time an element
    /// assignment can reference it.
    /// </remarks>
    /// <param name="arrayElementAssignment">The array element assignment statement to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    private void TransformArrayElementAssignment(ArrayElementAssignmentNode arrayElementAssignment, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        UtopIRVariable array = new(arrayElementAssignment.ArrayName);
        UtopIROperand indexOperand = this.TransformExpression(arrayElementAssignment.Index, instructions, declaredTypes);
        UtopIROperand value = this.TransformExpression(arrayElementAssignment.Value, instructions, declaredTypes);
        UtopIRType elementType = this.arrayElementTypes[arrayElementAssignment.ArrayName];

        if (this.IsCastableType(elementType))
        {
            UtopIRType valueType = this.InferOperandType(value, declaredTypes);
            value = this.CastOperandIfNeeded(value, valueType, elementType, instructions, declaredTypes);
        }

        instructions.Add(new AppointVictimInstruction(array, indexOperand, value));
    }

    /// <summary>
    /// Transforms a <see cref="PointerDeclarationNode"/> into a <see cref="WelcomeGallerypicInstruction"/>
    /// followed by either a <see cref="PicturetoInstruction"/> or an <see cref="AppointInstruction"/>.
    /// </summary>
    /// <remarks>
    /// When the initial value is an <see cref="AddressOfExpressionNode"/>, a <see cref="PicturetoInstruction"/>
    /// targets the declared pointer directly: <c>pictureto</c> only ever targets an already declared
    /// variable, so this deliberately bypasses <see cref="TransformExpression"/> and its temporary-register
    /// handling. Otherwise, an <see cref="AppointInstruction"/> assigns the <see cref="NaughtLiteral"/>
    /// singleton, for an absent or explicit <c>NAUGHT</c> initial value.
    /// </remarks>
    /// <param name="declaration">The pointer declaration statement to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    private void TransformPointerDeclaration(PointerDeclarationNode declaration, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        UtopIRVariable target = new(declaration.Name);
        UtopIRType pointeeType = this.MapType(declaration.PointeeType);

        instructions.Add(new WelcomeGallerypicInstruction(target, pointeeType));
        declaredTypes[declaration.Name] = UtopIRType.Pointer;
        this.pointerPointeeTypes[declaration.Name] = pointeeType;

        if (declaration.InitialValue is AddressOfExpressionNode addressOf)
        {
            instructions.Add(new PicturetoInstruction(target, new UtopIRVariable(addressOf.VariableName)));
        }
        else
        {
            instructions.Add(new AppointInstruction(target, new LiteralOperand(NaughtLiteral.Instance)));
        }
    }

    /// <summary>
    /// Transforms a <see cref="DereferenceAssignmentNode"/> into a <see cref="ViewtoInstruction"/>,
    /// flattening the value expression first if needed.
    /// </summary>
    /// <param name="dereferenceAssignment">The dereference assignment statement to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    private void TransformDereferenceAssignment(DereferenceAssignmentNode dereferenceAssignment, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        UtopIRVariable pointer = new(dereferenceAssignment.PointerName);
        UtopIROperand value = this.TransformExpression(dereferenceAssignment.Value, instructions, declaredTypes);
        UtopIRType pointeeType = this.pointerPointeeTypes[dereferenceAssignment.PointerName];

        if (this.IsCastableType(pointeeType))
        {
            UtopIRType valueType = this.InferOperandType(value, declaredTypes);
            value = this.CastOperandIfNeeded(value, valueType, pointeeType, instructions, declaredTypes);
        }

        instructions.Add(new ViewtoInstruction(pointer, value));
    }

    /// <summary>
    /// Transforms a <see cref="ProgrammeReturnNode"/> into a <see cref="FindInstruction"/>,
    /// flattening the return-value expression first if needed.
    /// </summary>
    /// <param name="programmeReturn">The programme return statement to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    private void TransformProgrammeReturn(ProgrammeReturnNode programmeReturn, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        UtopIROperand value = this.TransformExpression(programmeReturn.Value, instructions, declaredTypes);
        instructions.Add(new FindInstruction(value));
    }

    /// <summary>
    /// Transforms a <c>THAT WILL DO.</c> break statement into a <see cref="SailInstruction"/>
    /// targeting the closing label of the innermost enclosing switch or loop.
    /// </summary>
    /// <param name="instructions">The instruction list being built.</param>
    /// <exception cref="InvalidOperationException">Thrown when there is no enclosing switch or loop.</exception>
    private void TransformBreak(List<UtopIRInstruction> instructions)
    {
        if (this.breakTargets.Count == 0)
        {
            throw new InvalidOperationException(
                "A THAT WILL DO. break statement was encountered with no enclosing switch or loop block.");
        }

        instructions.Add(new SailInstruction(this.breakTargets.Peek()));
    }

    /// <summary>
    /// Transforms a <c>ONCE MORE.</c> continue statement into a <see cref="SailInstruction"/>
    /// targeting the continue target of the innermost enclosing loop.
    /// </summary>
    /// <param name="instructions">The instruction list being built.</param>
    /// <exception cref="InvalidOperationException">Thrown when there is no enclosing loop.</exception>
    private void TransformContinue(List<UtopIRInstruction> instructions)
    {
        if (this.continueTargets.Count == 0)
        {
            throw new InvalidOperationException(
                "An ONCE MORE. continue statement was encountered with no enclosing loop.");
        }

        instructions.Add(new SailInstruction(this.continueTargets.Peek()));
    }

    /// <summary>
    /// Transforms a <see cref="ConditionalNode"/> into a comparison/branch sequence.
    /// </summary>
    /// <remarks>
    /// <see cref="ConditionalNode.Condition"/> and every <see cref="ElseIfBranch.Condition"/> are
    /// transformed and their comparison/logical instructions emitted, in source order, before any
    /// branch is taken. This differs from <c>Interpreter.ExecuteConditional</c>, which evaluates
    /// lazily and short-circuits at the first true branch.
    /// </remarks>
    /// <param name="node">The conditional statement to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    private void TransformConditional(ConditionalNode node, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        string conditionText = this.BuildConditionText(node.Condition);
        List<string> elseIfConditionTexts = [.. node.ElseIfs.Select(branch => this.BuildConditionText(branch.Condition))];
        ConditionalLabels labels = this.labelFormatter.ForConditional(node, conditionText, elseIfConditionTexts);

        UtopIRLabel closing = labels.ClosingLabel;
        UtopIRLabel trueLabel = labels.TrueLabel;
        IReadOnlyList<UtopIRLabel> elseIfLabels = labels.ElseIfLabels;

        bool hasElse = node.ElseBlock.Count > 0;
        UtopIRLabel elseLabel = labels.ElseLabel;
        UtopIRLabel fallback = hasElse
            ? elseLabel
            : closing;

        UtopIROperand trueOperand = this.TransformExpression(node.Condition, instructions, declaredTypes);
        List<UtopIROperand> elseIfOperands = new(node.ElseIfs.Count);
        foreach (ElseIfBranch branch in node.ElseIfs)
        {
            elseIfOperands.Add(this.TransformExpression(branch.Condition, instructions, declaredTypes));
        }

        instructions.Add(new SailAlikeInstruction(trueOperand, trueLabel));
        for (int i = 0; i < node.ElseIfs.Count; i++)
        {
            instructions.Add(new SailAlikeInstruction(elseIfOperands[i], elseIfLabels[i]));
        }

        instructions.Add(new SailInstruction(fallback));

        instructions.Add(new LabelInstruction(trueLabel));
        foreach (Statement statement in node.TrueBlock)
        {
            this.TransformStatement(statement, instructions, declaredTypes);
        }

        AddClosingSailUnlessUnreachable(instructions, closing);

        for (int i = 0; i < node.ElseIfs.Count; i++)
        {
            instructions.Add(new LabelInstruction(elseIfLabels[i]));
            foreach (Statement statement in node.ElseIfs[i].Block)
            {
                this.TransformStatement(statement, instructions, declaredTypes);
            }

            AddClosingSailUnlessUnreachable(instructions, closing);
        }

        if (hasElse)
        {
            instructions.Add(new LabelInstruction(elseLabel));
            foreach (Statement statement in node.ElseBlock)
            {
                this.TransformStatement(statement, instructions, declaredTypes);
            }
        }

        instructions.Add(new LabelInstruction(closing));
    }

    /// <summary>
    /// Appends an unconditional <c>sail</c> to <paramref name="closing"/>, unless it would be
    /// unreachable.
    /// </summary>
    /// <remarks>
    /// A branch already ending in its own unconditional <c>sail</c> (from a trailing
    /// <c>THAT WILL DO.</c> or <c>ONCE MORE.</c>) makes a further <c>sail</c> to the closing label
    /// dead code, so it is skipped.
    /// </remarks>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="closing">The closing label of the construct.</param>
    private static void AddClosingSailUnlessUnreachable(List<UtopIRInstruction> instructions, UtopIRLabel closing)
    {
        if (instructions.Count == 0 || instructions[^1] is not SailInstruction)
        {
            instructions.Add(new SailInstruction(closing));
        }
    }

    /// <summary>
    /// Transforms a <see cref="GuardNode"/> into a comparison/branch sequence.
    /// </summary>
    /// <remarks>
    /// <see cref="GuardNode"/> has no true-branch body of its own: a passing guard has no effect at
    /// all, matching <c>Interpreter.ExecuteGuard</c>.  A <c>sailunlike</c> branches directly to the
    /// else block when the condition is false; when true, an unconditional <c>sail</c> immediately
    /// after skips past it to the closing label.
    /// </remarks>
    /// <param name="node">The guard statement to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    private void TransformGuard(GuardNode node, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        GuardLabels labels = this.labelFormatter.ForGuard(node);
        UtopIRLabel elseLabel = labels.ElseLabel;
        UtopIRLabel closing = labels.ClosingLabel;

        UtopIROperand conditionOperand = this.TransformExpression(node.Condition, instructions, declaredTypes);
        instructions.Add(new SailUnlikeInstruction(conditionOperand, elseLabel));
        instructions.Add(new SailInstruction(closing));

        instructions.Add(new LabelInstruction(elseLabel));
        foreach (Statement statement in node.ElseBlock)
        {
            this.TransformStatement(statement, instructions, declaredTypes);
        }

        instructions.Add(new LabelInstruction(closing));
    }

    /// <summary>
    /// Transforms a <see cref="SwitchNode"/> into a comparison/branch sequence.
    /// </summary>
    /// <remarks>
    /// A <see cref="SwitchCase"/> with an empty <see cref="SwitchCase.Block"/> falls through into
    /// the next case, since no <c>sail</c> is emitted for an empty block.  The closing label is
    /// pushed onto <see cref="breakTargets"/> for the whole transformation, so <c>THAT WILL DO.</c>
    /// inside any case body targets this switch even when nested inside a loop.
    /// </remarks>
    /// <param name="node">The switch statement to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    private void TransformSwitch(SwitchNode node, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        List<string> caseTexts = [.. node.Cases.Select(switchCase => this.SwitchCaseExpressionText(switchCase.Literal))];
        SwitchLabels labels = this.labelFormatter.ForSwitch(node, caseTexts);
        UtopIRLabel closing = labels.ClosingLabel;
        UtopIRLabel defaultLabel = labels.DefaultLabel;
        IReadOnlyList<UtopIRLabel> caseLabels = labels.CaseLabels;
        bool hasDefault = node.DefaultBlock.Count > 0;

        this.breakTargets.Push(closing);
        try
        {
            UtopIROperand switchOperand = this.TransformExpression(node.Expression, instructions, declaredTypes);
            UtopIRType switchType = this.InferOperandType(switchOperand, declaredTypes);

            for (int i = 0; i < node.Cases.Count; i++)
            {
                SwitchCase switchCase = node.Cases[i];
                UtopIRLabel caseLabel = caseLabels[i];

                UtopIROperand compareLeft = switchOperand;
                UtopIROperand compareRight = new LiteralOperand(switchCase.Literal!);
                UtopIRComparisonOperation operation = UtopIRComparisonOperation.Alike;

                if (this.IsCastableType(switchType) && switchCase.Literal is not string)
                {
                    UtopIRType literalType = this.InferOperandType(compareRight, declaredTypes);
                    UtopIRType widenedType = this.Widen(switchType, literalType);
                    compareLeft = this.CastOperandIfNeeded(compareLeft, switchType, widenedType, instructions, declaredTypes);
                    compareRight = this.CastOperandIfNeeded(compareRight, literalType, widenedType, instructions, declaredTypes);
                    if (this.IsFloatType(widenedType))
                    {
                        operation = UtopIRComparisonOperation.AlikeFloat;
                    }
                }

                string mnemonic = this.ComparisonOperationMnemonic(operation);
                string temporaryVariableName = this.formatter.CreateName(mnemonic, this.OperandName(compareLeft), this.OperandName(compareRight));
                UtopIRVariable temporaryVariable = new(temporaryVariableName);
                instructions.Add(new ComparisonInstruction(operation, temporaryVariable, compareLeft, compareRight));
                declaredTypes[temporaryVariableName] = UtopIRType.Decree;

                instructions.Add(new SailAlikeInstruction(new VariableOperand(temporaryVariable), caseLabel));
            }

            instructions.Add(new SailInstruction(hasDefault ? defaultLabel : closing));

            for (int i = 0; i < node.Cases.Count; i++)
            {
                instructions.Add(new LabelInstruction(caseLabels[i]));
                foreach (Statement statement in node.Cases[i].Block)
                {
                    this.TransformStatement(statement, instructions, declaredTypes);
                }
            }

            if (hasDefault)
            {
                instructions.Add(new LabelInstruction(defaultLabel));
                foreach (Statement statement in node.DefaultBlock)
                {
                    this.TransformStatement(statement, instructions, declaredTypes);
                }
            }

            instructions.Add(new LabelInstruction(closing));
        }
        finally
        {
            this.breakTargets.Pop();
        }
    }

    /// <summary>
    /// Dispatches a <see cref="LoopNode"/> to the transform method matching its
    /// <see cref="LoopNode.Type"/>.
    /// </summary>
    /// <param name="node">The loop statement to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    /// <exception cref="ArgumentOutOfRangeException">Thrown when <see cref="LoopNode.Type"/> is not a recognised <see cref="LoopType"/>.</exception>
    private void TransformLoop(LoopNode node, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        switch (node.Type)
        {
            case LoopType.Infinite:
                this.TransformInfiniteLoop(node, instructions, declaredTypes);
                break;
            case LoopType.Whilst:
                this.TransformWhilstLoop(node, instructions, declaredTypes);
                break;
            case LoopType.Ascending:
                this.TransformCountedLoop(node, instructions, declaredTypes, ascending: true);
                break;
            case LoopType.Descending:
                this.TransformCountedLoop(node, instructions, declaredTypes, ascending: false);
                break;
            default:
                throw new ArgumentOutOfRangeException(nameof(node), node.Type, "Unknown loop type.");
        }
    }

    /// <summary>
    /// Transforms an infinite (<see cref="LoopType.Infinite"/>) <see cref="LoopNode"/>.
    /// </summary>
    /// <remarks>
    /// No condition exists to check: the loop can only be exited via <c>THAT WILL DO.</c>.  A
    /// continue reuses the opening label directly since there is no per-iteration mechanism, such
    /// as the increment of a counted loop, that a continue must still let run.
    /// </remarks>
    /// <param name="node">The loop statement to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    private void TransformInfiniteLoop(LoopNode node, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        LoopLabels labels = this.labelFormatter.ForLoop(node, conditionText: null);
        UtopIRLabel opening = labels.OpeningLabel;
        UtopIRLabel closing = labels.ClosingLabel;

        this.breakTargets.Push(closing);
        this.continueTargets.Push(labels.ContinueLabel ?? opening);
        try
        {
            instructions.Add(new LabelInstruction(opening));
            foreach (Statement statement in node.Body)
            {
                this.TransformStatement(statement, instructions, declaredTypes);
            }

            instructions.Add(new SailInstruction(opening));
            instructions.Add(new LabelInstruction(closing));
        }
        finally
        {
            this.breakTargets.Pop();
            this.continueTargets.Pop();
        }
    }

    /// <summary>
    /// Transforms a <see cref="LoopType.Whilst"/> <see cref="LoopNode"/>.
    /// </summary>
    /// <remarks>
    /// The opening label is both the condition-check point, checked before every iteration,
    /// including the first, matching <c>Interpreter.ExecuteWhilstLoop</c>, and the continue target.
    /// A continue can safely reuse it directly since a Whilst loop has no per-iteration mechanism,
    /// such as the increment of a counted loop, that a continue must still let run.
    /// </remarks>
    /// <param name="node">The loop statement to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    private void TransformWhilstLoop(LoopNode node, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        LoopLabels labels = this.labelFormatter.ForLoop(node, this.BuildConditionText(node.Condition!));
        UtopIRLabel opening = labels.OpeningLabel;
        UtopIRLabel closing = labels.ClosingLabel;

        this.breakTargets.Push(closing);
        this.continueTargets.Push(labels.ContinueLabel ?? opening);
        try
        {
            instructions.Add(new LabelInstruction(opening));
            UtopIROperand conditionOperand = this.TransformExpression(node.Condition!, instructions, declaredTypes);
            instructions.Add(new SailUnlikeInstruction(conditionOperand, closing));

            foreach (Statement statement in node.Body)
            {
                this.TransformStatement(statement, instructions, declaredTypes);
            }

            instructions.Add(new SailInstruction(opening));
            instructions.Add(new LabelInstruction(closing));
        }
        finally
        {
            this.breakTargets.Pop();
            this.continueTargets.Pop();
        }
    }

    /// <summary>
    /// Transforms a <see cref="LoopType.Ascending"/> or <see cref="LoopType.Descending"/>
    /// <see cref="LoopNode"/>.
    /// </summary>
    /// <remarks>
    /// The condition is checked before every iteration, including the first, exiting via
    /// <c>sailalike</c> if already true. Continue cannot reuse the opening label directly, since
    /// the increment or decrement must still run after a continue (only a break skips it), so
    /// continue instead targets a dedicated label placed after the body but before the step.
    /// <see cref="LoopNode.Step"/> is transformed dynamically each time it is present, otherwise
    /// the default step is a type-matched literal <c>1</c>. <see cref="LoopNode.LoopVariable"/> is
    /// always an already-declared outer variable; the loop itself never declares it.
    /// </remarks>
    /// <param name="node">The loop statement to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    /// <param name="ascending"><c>true</c> for <see cref="LoopType.Ascending"/> (uses <c>sum</c>), or <c>false</c> for <see cref="LoopType.Descending"/> (uses <c>diff</c>).</param>
    private void TransformCountedLoop(LoopNode node, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes, bool ascending)
    {
        LoopLabels labels = this.labelFormatter.ForLoop(node, this.BuildConditionText(node.Condition!));
        UtopIRLabel opening = labels.OpeningLabel;
        UtopIRLabel continueLabel = labels.ContinueLabel!;
        UtopIRLabel closing = labels.ClosingLabel;

        this.breakTargets.Push(closing);
        this.continueTargets.Push(continueLabel);
        try
        {
            instructions.Add(new LabelInstruction(opening));
            UtopIROperand conditionOperand = this.TransformExpression(node.Condition!, instructions, declaredTypes);
            instructions.Add(new SailAlikeInstruction(conditionOperand, closing));

            foreach (Statement statement in node.Body)
            {
                this.TransformStatement(statement, instructions, declaredTypes);
            }

            instructions.Add(new LabelInstruction(continueLabel));
            UtopIRVariable loopVariable = new(node.LoopVariable!);
            UtopIRType loopVariableType = declaredTypes[node.LoopVariable!];

            UtopIROperand stepOperand;
            if (node.Step is not null)
            {
                UtopIROperand rawStep = this.TransformExpression(node.Step, instructions, declaredTypes);
                UtopIRType rawStepType = this.InferOperandType(rawStep, declaredTypes);
                stepOperand = this.CastOperandIfNeeded(rawStep, rawStepType, loopVariableType, instructions, declaredTypes);
            }
            else
            {
                stepOperand = new LiteralOperand(this.CreateOneLiteral(loopVariableType));
            }

            UtopIRArithmeticOperation operation = ascending ? UtopIRArithmeticOperation.Sum : UtopIRArithmeticOperation.Diff;
            string mnemonic = this.OperationMnemonic(operation);
            string temporaryVariableName = this.formatter.CreateName(mnemonic, this.OperandName(new VariableOperand(loopVariable)), this.OperandName(stepOperand));
            UtopIRVariable temporaryVariable = new(temporaryVariableName);
            instructions.Add(new ArithmeticInstruction(operation, temporaryVariable, new VariableOperand(loopVariable), stepOperand));
            declaredTypes[temporaryVariableName] = loopVariableType;
            instructions.Add(new AppointInstruction(loopVariable, new VariableOperand(temporaryVariable)));

            instructions.Add(new SailInstruction(opening));
            instructions.Add(new LabelInstruction(closing));
        }
        finally
        {
            this.breakTargets.Pop();
            this.continueTargets.Pop();
        }
    }

    /// <summary>
    /// Transforms an expression into a <see cref="UtopIROperand"/>, emitting any necessary
    /// intermediate arithmetic instructions first.
    /// </summary>
    /// <param name="expression">The expression to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    /// <returns>
    /// A <see cref="LiteralOperand"/> for literal nodes, a <see cref="VariableOperand"/> for
    /// identifier nodes or a <see cref="VariableOperand"/> referencing a newly emitted
    /// temporary register for arithmetic expressions.
    /// </returns>
    /// <exception cref="NotSupportedException">Thrown when the expression type is not supported in the current transformer scope.</exception>
    private UtopIROperand TransformExpression(Expression expression, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        switch (expression)
        {
            case LiteralNode { Type: LiteralType.Null }:
                return new LiteralOperand(NaughtLiteral.Instance);
            case LiteralNode literal:
                return new LiteralOperand(literal.Value!);
            case IdentifierNode identifier:
                return new VariableOperand(new UtopIRVariable(identifier.Name));
            case PrefixExpressionNode prefix when this.IsArithmeticOperator(prefix.Operator) && this.IsPointerOperand(prefix.Arguments[0], declaredTypes):
                return this.TransformPointerArithmetic(prefix, instructions, declaredTypes);
            case PrefixExpressionNode prefix when this.IsArithmeticOperator(prefix.Operator):
                return this.TransformArithmetic(prefix, instructions, declaredTypes);
            case PrefixExpressionNode prefix when this.IsBitwiseOperator(prefix.Operator):
                return this.TransformBitwise(prefix, instructions, declaredTypes);
            case PrefixExpressionNode prefix when this.IsComparisonOperator(prefix.Operator):
                return this.TransformComparison(prefix, instructions, declaredTypes);
            case PrefixExpressionNode prefix when this.IsLogicalOperator(prefix.Operator):
                return this.TransformLogical(prefix, instructions, declaredTypes);
            case PrefixExpressionNode prefix when prefix.Operator == Operator.Summon:
                return this.TransformSummonFind(prefix, instructions, declaredTypes);
            case ExpressionCastNode cast:
                return this.TransformCast(cast, instructions, declaredTypes);
            case TernaryExpressionNode ternary:
                return this.TransformTernary(ternary, instructions, declaredTypes);
            case ArrayIndexNode arrayIndex when declaredTypes[arrayIndex.ArrayName] == UtopIRType.Yarn:
                return this.TransformVictimYarn(arrayIndex, instructions, declaredTypes);
            case ArrayIndexNode arrayIndex when declaredTypes[arrayIndex.ArrayName] == UtopIRType.Array:
                return this.TransformVictimList(arrayIndex, instructions, declaredTypes);
            case AddressOfExpressionNode addressOf:
                return this.TransformAddressOf(addressOf, instructions, declaredTypes);
            case DereferenceExpressionNode dereference:
                return this.TransformViewfrom(dereference, instructions, declaredTypes);
            default:
                throw new NotSupportedException(
                    $"Expression type '{expression.GetType().Name}' with operator " +
                    $"'{(expression is PrefixExpressionNode prefixExpression ? prefixExpression.Operator : "(none)")}' " +
                    $"is not supported by the transformer in this version.");
        }
    }

    /// <summary>
    /// Resolves a <c>SUMMON</c> prefix expression to a function, transforming and pushing each argument
    /// as a <see cref="PrenticeInstruction"/> in declaration order.
    /// </summary>
    /// <param name="prefix">The <c>SUMMON</c> prefix expression.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    /// <returns>The resolved function reference and its bound descriptor.</returns>
    /// <remarks>
    /// <para>
    /// Checks <see cref="userFunctionNames"/> before the function catalogue, so that a name clash
    /// resolves the same way it would at runtime: a user-defined function always takes priority over a
    /// catalogue function of the same name.
    /// </para>
    /// <para>
    /// Current limitation: since lowering a call to a user-defined function body is not yet supported,
    /// a name found in <see cref="userFunctionNames"/> currently throws the same "user-defined function
    /// lowering is not supported" error as any other call to a user-defined function, rather than
    /// resolving to a catalogue function of the same name. Only the global tier of function resolution
    /// is supported, since UtopIR has no namespace concept yet.
    /// </para>
    /// </remarks>
    /// <exception cref="NotSupportedException">
    /// Thrown when the first argument is not a function name, the name is user-defined, or the name is
    /// not found in the external function catalogue.
    /// </exception>
    private (FunctionReference Function, BoundFunctionDescriptor Descriptor) ResolveSummon(PrefixExpressionNode prefix, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        if (prefix.Arguments.Count == 0 || prefix.Arguments[0] is not IdentifierNode functionIdentifier)
        {
            throw new NotSupportedException("SUMMON requires a function name as its first argument.");
        }

        string functionName = functionIdentifier.Name;
        if (this.userFunctionNames.Contains(functionName))
        {
            throw new NotSupportedException(
                $"Function '{functionName}' is user-defined; user-defined function lowering is not supported by the transformer in this version.");
        }

        BoundFunctionDescriptor descriptor = this.externalFunctions.Find(functionName)
            ?? throw new NotSupportedException($"Function '{functionName}' is not defined.");

        for (int i = 0; i < descriptor.Parameters.Count; i++)
        {
            UtopIROperand argument = this.TransformExpression(prefix.Arguments[i + 1], instructions, declaredTypes);
            UtopIRType parameterType = this.MapType(descriptor.Parameters[i].Type);
            if (this.IsCastableType(parameterType))
            {
                UtopIRType argumentType = this.InferOperandType(argument, declaredTypes);
                argument = this.CastOperandIfNeeded(argument, argumentType, parameterType, instructions, declaredTypes);
            }

            instructions.Add(new PrenticeInstruction(argument));
        }

        return (new FunctionReference(functionName), descriptor);
    }

    /// <summary>
    /// Transforms a <c>SUMMON</c> statement into <see cref="PrenticeInstruction"/>s followed by a
    /// <see cref="SummonInstruction"/>, discarding any return value.
    /// </summary>
    /// <param name="prefix">The <c>SUMMON</c> prefix expression.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    private void TransformSummonStatement(PrefixExpressionNode prefix, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        (FunctionReference function, _) = this.ResolveSummon(prefix, instructions, declaredTypes);
        instructions.Add(new SummonInstruction(function));
    }

    /// <summary>
    /// Transforms a <c>SUMMON</c> expression into <see cref="PrenticeInstruction"/>s followed by a
    /// <see cref="SummonFindInstruction"/> into a new temporary register.
    /// </summary>
    /// <param name="prefix">The <c>SUMMON</c> prefix expression.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    /// <returns>A <see cref="VariableOperand"/> referencing the temporary register holding the returned value.</returns>
    /// <exception cref="NotSupportedException">Thrown when the resolved function is void.</exception>
    private UtopIROperand TransformSummonFind(PrefixExpressionNode prefix, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        (FunctionReference function, BoundFunctionDescriptor descriptor) = this.ResolveSummon(prefix, instructions, declaredTypes);
        if (descriptor.ReturnType is null)
        {
            throw new NotSupportedException($"Function '{function.Name}' is void and cannot be used in expression position.");
        }

        UtopIRType returnType = this.MapType(descriptor.ReturnType.Value);
        string temporaryVariableName = this.formatter.CreateName(UtopIRKeywords.Instructions.SummonFind, function.Name);
        UtopIRVariable temporaryVariable = new(temporaryVariableName);
        instructions.Add(new SummonFindInstruction(temporaryVariable, function));
        declaredTypes[temporaryVariableName] = returnType;
        return new VariableOperand(temporaryVariable);
    }

    /// <summary>
    /// Transforms a <see cref="PrintNode"/> (<c>BEHOLD</c>) into a call to its Standard Library
    /// function.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Unlike <see cref="ResolveSummon"/>, this deliberately does not apply the <see cref="userFunctionNames"/>
    /// shadowing check: <c>BEHOLD</c> is a language keyword, not a name the programme chose, so it always
    /// calls the real Standard Library function regardless of whether the programme happens to define its own
    /// function of that name.
    /// </para>
    /// <para>
    /// Supports a plain string literal with no <c>{...}</c> interpolation placeholder, or a <c>yarn</c>-typed
    /// variable, since both are already the CLR <see cref="string"/> the Standard Library function expects,
    /// with no conversion needed. <c>PrintNode.Expression</c> can be any <see cref="LiteralType"/> at runtime,
    /// converted via <c>ToString()</c>, and the resulting text is then interpolated against the live
    /// environment (see <c>Interpreter.ExecutePrint</c>/<c>Interpolate</c>): a non-<c>yarn</c> value has no
    /// UtopIR-level to-string conversion yet, and interpolation is expected to be resolved before a
    /// programme ever reaches UtopIR, not something this layer lowers, so both are rejected here rather
    /// than compiled incorrectly.
    /// </para>
    /// </remarks>
    /// <param name="print">The print statement.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>.</param>
    /// <exception cref="NotSupportedException">
    /// Thrown when <see cref="PrintNode.Expression"/> is neither a plain string literal with no
    /// interpolation placeholder nor a <c>yarn</c>-typed variable, or when the Standard Library function
    /// is not in the supplied catalogue.
    /// </exception>
    private void TransformPrint(PrintNode print, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        UtopIROperand textOperand = print.Expression switch
        {
            LiteralNode { Type: LiteralType.String, Value: string text } when !InterpolationPlaceholder.IsMatch(text) =>
                new LiteralOperand(text),
            IdentifierNode identifier when declaredTypes.TryGetValue(identifier.Name, out UtopIRType variableType) && variableType == UtopIRType.Yarn =>
                this.TransformExpression(identifier, instructions, declaredTypes),
            _ => throw new NotSupportedException(
                "BEHOLD is only supported by the transformer in this version for a plain string literal " +
                "with no '{...}' interpolation placeholder, or a yarn-typed variable.")
        };

        BoundFunctionDescriptor descriptor = this.externalFunctions.Find("PreviewBehold")
            ?? throw new NotSupportedException("The 'PreviewBehold' Standard Library function, required to lower BEHOLD, was not found in the supplied catalogue.");

        instructions.Add(new PrenticeInstruction(textOperand));
        instructions.Add(new PrenticeInstruction(new LiteralOperand(!print.SuppressNewline)));
        instructions.Add(new SummonInstruction(new FunctionReference(descriptor.Name)));
    }

    /// <summary>
    /// Transforms an <see cref="InputNode"/> (<c>PRAY TELL</c>) into a call to its Standard Library
    /// function, saved into the target variable.
    /// </summary>
    /// <remarks>
    /// Deliberately does not apply the <see cref="userFunctionNames"/> shadowing check, for the same
    /// reason as <see cref="TransformPrint"/>: <c>PRAY TELL</c> is a keyword, not a chosen name. Unlike
    /// <c>BEHOLD</c>, this is a complete, faithful lowering: the Standard Library function always returns a
    /// <c>yarn</c>, exactly matching the <c>InputNode.Target</c> required type, with no conversion involved.
    /// </remarks>
    /// <param name="input">The input statement.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>.</param>
    /// <exception cref="NotSupportedException">Thrown when the Standard Library function is not in the supplied catalogue.</exception>
    private void TransformInput(InputNode input, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        BoundFunctionDescriptor descriptor = this.externalFunctions.Find("PreviewPrayTell")
            ?? throw new NotSupportedException("The 'PreviewPrayTell' Standard Library function, required to lower PRAY TELL, was not found in the supplied catalogue.");

        string temporaryVariableName = this.formatter.CreateName(UtopIRKeywords.Instructions.SummonFind, descriptor.Name);
        UtopIRVariable temporaryVariable = new(temporaryVariableName);
        instructions.Add(new SummonFindInstruction(temporaryVariable, new FunctionReference(descriptor.Name)));
        declaredTypes[temporaryVariableName] = this.MapType(descriptor.ReturnType!.Value);

        instructions.Add(new AppointInstruction(new UtopIRVariable(input.Target), new VariableOperand(temporaryVariable)));
    }

    /// <summary>
    /// Collects the names of every <see cref="FunctionDefinitionNode"/> in a statement list, including nested ones.
    /// </summary>
    /// <param name="statements">The statements to scan.</param>
    /// <returns>The set of user-defined function names found.</returns>
    private static HashSet<string> CollectFunctionNames(IReadOnlyList<Statement> statements)
    {
        HashSet<string> names = [];
        CollectFunctionNamesInto(statements, names);
        return names;
    }

    /// <summary>
    /// Recursively walks a statement list, adding every <see cref="FunctionDefinitionNode"/> name found
    /// into <paramref name="names"/>.
    /// </summary>
    /// <param name="statements">The statements to scan.</param>
    /// <param name="names">The set to add discovered function names into.</param>
    private static void CollectFunctionNamesInto(IReadOnlyList<Statement> statements, HashSet<string> names)
    {
        foreach (Statement statement in statements)
        {
            if (statement is FunctionDefinitionNode function)
            {
                names.Add(function.Name);
                CollectFunctionNamesInto(function.Body, names);
            }
        }
    }

    /// <summary>
    /// Transforms a <see cref="ArrayIndexNode"/> referencing a <c>yarn</c> variable into a
    /// <see cref="VictimYarnInstruction"/> selecting the <c>stitch</c> character at the given index.
    /// </summary>
    /// <remarks>
    /// <see cref="ArrayIndexNode"/> (<c>VICTIM &lt;index&gt; ON &lt;name&gt;</c>) is shared between
    /// <c>yarn</c> character access and array element access (see <see cref="TransformVictimList"/>).
    /// <see cref="TransformExpression"/> only dispatches here when <paramref name="declaredTypes"/>
    /// records the <paramref name="arrayIndex"/> <see cref="ArrayIndexNode.ArrayName"/> as
    /// <see cref="UtopIRType.Yarn"/>.
    /// </remarks>
    /// <param name="arrayIndex">The array index expression to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    /// <returns>A <see cref="VariableOperand"/> for the temporary register holding the selected <c>stitch</c> character.</returns>
    private VariableOperand TransformVictimYarn(ArrayIndexNode arrayIndex, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        UtopIROperand yarnOperand = new VariableOperand(new UtopIRVariable(arrayIndex.ArrayName));
        UtopIROperand indexOperand = this.TransformExpression(arrayIndex.Index, instructions, declaredTypes);

        string temporaryVariableName = this.formatter.CreateName(UtopIRKeywords.Instructions.VictimYarn, arrayIndex.ArrayName, this.OperandName(indexOperand));
        UtopIRVariable temporaryVariable = new(temporaryVariableName);
        instructions.Add(new VictimYarnInstruction(temporaryVariable, yarnOperand, indexOperand));
        declaredTypes[temporaryVariableName] = UtopIRType.Stitch;
        return new VariableOperand(temporaryVariable);
    }

    /// <summary>
    /// Transforms a <see cref="ArrayIndexNode"/> referencing an array variable into a
    /// <see cref="VictimListInstruction"/> selecting the element at the given index.
    /// </summary>
    /// <remarks>
    /// <see cref="ArrayIndexNode"/> (<c>VICTIM &lt;index&gt; ON &lt;name&gt;</c>) is shared between
    /// array element access and <c>yarn</c> character access (see <see cref="TransformVictimYarn"/>).
    /// <see cref="TransformExpression"/> only dispatches here when <paramref name="declaredTypes"/>
    /// records the <paramref name="arrayIndex"/> <see cref="ArrayIndexNode.ArrayName"/> as
    /// <see cref="UtopIRType.Array"/>; the true type of the temporary register is looked up from
    /// <see cref="arrayElementTypes"/>, since <paramref name="declaredTypes"/> only ever records the
    /// <see cref="UtopIRType.Array"/> marker for the array itself.
    /// </remarks>
    /// <param name="arrayIndex">The array index expression to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    /// <returns>A <see cref="VariableOperand"/> for the temporary register holding the selected element.</returns>
    private VariableOperand TransformVictimList(ArrayIndexNode arrayIndex, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        UtopIRVariable array = new(arrayIndex.ArrayName);
        UtopIROperand indexOperand = this.TransformExpression(arrayIndex.Index, instructions, declaredTypes);
        UtopIRType elementType = this.arrayElementTypes[arrayIndex.ArrayName];

        string temporaryVariableName = this.formatter.CreateName(UtopIRKeywords.Instructions.VictimList, arrayIndex.ArrayName, this.OperandName(indexOperand));
        UtopIRVariable temporaryVariable = new(temporaryVariableName);
        instructions.Add(new VictimListInstruction(temporaryVariable, array, indexOperand));
        declaredTypes[temporaryVariableName] = elementType;
        return new VariableOperand(temporaryVariable);
    }

    /// <summary>
    /// Transforms an <see cref="AddressOfExpressionNode"/> into a <see cref="PicturetoInstruction"/>
    /// into a temporary register.
    /// </summary>
    /// <remarks>
    /// The pointee type recorded for the temporary is the own type of the addressed variable for a scalar,
    /// the element type of the array for an array (a pointer to an array points at its first element), or
    /// <see cref="UtopIRType.Stitch"/> for a <c>yarn</c> (a pointer to a string points at its first character).
    /// </remarks>
    /// <param name="addressOf">The address-of expression to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
    /// <param name="declaredTypes">The map from variable name to its known <see cref="UtopIRType"/>, used for widening.</param>
    /// <returns>A <see cref="VariableOperand"/> for the temporary register holding the new pointer.</returns>
    private VariableOperand TransformAddressOf(AddressOfExpressionNode addressOf, List<UtopIRInstruction> instructions, Dictionary<string, UtopIRType> declaredTypes)
    {
        UtopIRVariable pointee = new(addressOf.VariableName);
        UtopIRType variableType = declaredTypes[addressOf.VariableName];
        UtopIRType pointeeType = variableType switch
        {
            UtopIRType.Array => this.arrayElementTypes[addressOf.VariableName],
            UtopIRType.Yarn => UtopIRType.Stitch,
            _ => variableType
        };

        string temporaryVariableName = this.formatter.CreateName(UtopIRKeywords.Instructions.PictureTo, addressOf.VariableName);
        UtopIRVariable temporaryVariable = new(temporaryVariableName);
        instructions.Add(new PicturetoInstruction(temporaryVariable, pointee));
        declaredTypes[temporaryVariableName] = UtopIRType.Pointer;
        this.pointerPointeeTypes[temporaryVariableName] = pointeeType;
        return new VariableOperand(temporaryVariable);
    }

    /// <summary>
    /// Transforms a <see cref="DereferenceExpressionNode"/> into a <see cref="ViewfromInstruction"/>
    /// into a temporary register.
    /// </summary>
    /// <param name="dereference">The dereference expression to transform.</param>
    /// <param name="instructions">The instruction list being built.</param>
